#!/usr/bin/env python3
"""Regenerate the checked-in Java service facades from tools/sdk-schema.json."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = json.loads((ROOT / 'tools/sdk-schema.json').read_text())
OUTPUT = ROOT / 'src/main/java/com/onepassword/sdk'

for name, methods in SCHEMA['apis'].items():
    source = ('// Generated by tools/generate_api.py. See THIRD_PARTY_NOTICES.md.\n'
              'package com.onepassword.sdk;\n\n'
              'import com.fasterxml.jackson.core.type.TypeReference;\n'
              'import com.onepassword.sdk.internal.Checks;\n'
              'import com.onepassword.sdk.internal.Json;\n'
              'import com.onepassword.sdk.internal.Session;\n'
              'import com.onepassword.sdk.model.*;\n'
              'import java.lang.ref.Reference;\nimport java.util.List;\nimport java.util.Objects;\n\n')
    source += f'/** {name} operations on an authenticated client. */\npublic final class {name} {{\n'
    source += '    private final Session session;\n'
    source += '    // Keeps the client and its Cleaner registration alive while a facade is in use.\n'
    source += '    private final Client owner;\n'
    if name == 'Items':
        source += '    private final ItemsFiles files;\n    private final ItemsShares shares;\n'
    source += f'\n    {name}(Client owner, Session session) {{\n        this.owner = owner;\n        this.session = session;\n'
    if name == 'Items':
        source += '        files = new ItemsFiles(owner, session);\n        shares = new ItemsShares(owner, session);\n'
    source += '    }\n\n'
    if name == 'Items':
        source += '    public ItemsFiles files() { return files; }\n    public ItemsShares shares() { return shares; }\n\n'
    for method in methods:
        args = method['args']
        source += '    /** ' + method['doc'].replace('*/', '* /') + ' */\n'
        source += f'    public {method["result"]} {method["name"]}(' + ', '.join(t + ' ' + n for t, n, wire in args) + ') {\n'
        source += '        try {\n'
        values = []
        for typ, field, wire in args:
            value = field
            if field in method.get('nullable', []):
                pass
            elif typ == 'String':
                value = f'Checks.notBlank({field}, "{field}")'
            elif typ.startswith('List<') or typ.endswith('...'):
                value = f'List.{"of" if typ.endswith("...") else "copyOf"}({field})'
            else:
                value = f'Objects.requireNonNull({field}, "{field}")'
            values += [f'"{wire}"', value]
        invocation = f'session.invoke("{method["wire"]}", Json.parameters(' + ', '.join(values) + ')'
        result = method['result']
        if result == 'void':
            source += f'            {invocation});\n'
        else:
            reader = f'new TypeReference<{result}>() {{}}' if '<' in result else result + '.class'
            source += f'            return {invocation}, {reader});\n'
        source += '        } finally {\n            Reference.reachabilityFence(owner);\n        }\n'
        source += '    }\n\n'
    if name == 'Vaults':
        source += '    public List<VaultOverview> list() { return list(null); }\n\n'
        source += '    public Vault get(String vaultId) { return get(vaultId, new VaultGetParams(null)); }\n\n'
    if name == 'Groups':
        source += '    public Group get(String groupId) { return get(groupId, new GroupGetParams(null)); }\n\n'
    if name == 'Secrets':
        source += ('    /** Validates syntax locally, without authentication. */\n'
                   '    public static void validateSecretReference(String reference) {\n'
                   '        new SecretUtilities().validateSecretReference(reference);\n    }\n\n'
                   '    /** Generates a password locally using the native core. */\n'
                   '    public static GeneratePasswordResponse generatePassword(PasswordRecipe recipe) {\n'
                   '        return new SecretUtilities().generatePassword(recipe);\n    }\n')
    source += '}\n'
    (OUTPUT / f'{name}.java').write_text(source)
