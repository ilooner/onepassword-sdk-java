#!/usr/bin/env python3
"""Regenerate checked-in Java value types from the pinned SDK wire schema.

Run from any directory: python3 tools/generate_models.py
The schema is derived from 1Password's MIT-licensed Go SDK types.go; see notices.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = json.loads((ROOT / 'tools/sdk-schema.json').read_text())
OUTPUT = ROOT / 'src/main/java/com/onepassword/sdk/model'
HEADER = '// Generated by tools/generate_models.py. See THIRD_PARTY_NOTICES.md.\n'
PACKAGE = 'package com.onepassword.sdk.model;\n\n'


def constant(name):
    name = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', name)
    return re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', name).upper()


def write(name, source):
    (OUTPUT / f'{name}.java').write_text(HEADER + PACKAGE + source)


def java_type(go):
    if go.startswith('*'):
        return {'bool': 'Boolean', 'uint32': 'Long'}.get(go[1:], java_type(go[1:]))
    if go == '[]byte':
        return 'byte[]'
    if go.startswith('[]'):
        return 'List<' + java_type(go[2:]) + '>'
    if go.startswith('map[string]'):
        return 'Map<String, ' + java_type(go[len('map[string]'):]) + '>'
    if go.startswith('Response['):
        inner = go[len('Response['):-1].split(', ')
        return 'Response<' + ', '.join(java_type(t) for t in inner) + '>'
    return {'string': 'String', 'bool': 'boolean', 'uint32': 'long',
            'time.Time': 'Instant', 'struct{}': 'Void', 'ErrorMessage': 'String'}.get(go, go)


for name, values in SCHEMA['enums'].items():
    entries = []
    for suffix, wire in values:
        annotation = '    @JsonEnumDefaultValue\n' if suffix == 'Unsupported' else ''
        entries.append(annotation + f'    @JsonProperty("{wire}") {constant(suffix)}')
    write(name, 'import com.fasterxml.jackson.annotation.JsonEnumDefaultValue;\n'
          'import com.fasterxml.jackson.annotation.JsonProperty;\n\n'
          f'/** Wire values for {name}. */\npublic enum {name} {{\n'
          + ',\n'.join(entries) + '\n}\n')

for name, fields in SCHEMA['records'].items():
    fields = [(java_type(f['type']), f['name'], f) for f in fields]
    source = ('import java.time.Instant;\nimport java.util.Arrays;\nimport java.util.List;\n'
              'import java.util.Map;\nimport java.util.Objects;\n'
              'import com.onepassword.sdk.internal.Checks;\n\n')
    source += f'/** Immutable {name} value. Optional properties may be null. */\n'
    source += f'public record {name}(\n' + ',\n'.join('        ' + t + ' ' + n for t, n, f in fields) + ') {\n'
    source += f'    public {name} {{\n'
    for typ, field, meta in fields:
        optional = meta['optional']
        if typ.startswith('List<') or typ.startswith('Map<'):
            kind = 'List' if typ.startswith('List<') else 'Map'
            default = 'null' if optional else f'{kind}.of()'
            source += f'        {field} = {field} == null ? {default} : {kind}.copyOf({field});\n'
        elif typ == 'byte[]':
            source += f'        {field} = Objects.requireNonNull({field}, "{field}").clone();\n'
        elif typ in ('long', 'Long'):
            check = f'Checks.unsignedInt({field}, "{field}");'
            source += f'        if ({field} != null) {{ {check} }}\n' if typ == 'Long' else f'        {check}\n'
        elif typ != 'boolean' and not optional:
            source += f'        Objects.requireNonNull({field}, "{field}");\n'
    source += '    }\n\n'
    for typ, field, meta in fields:
        if typ == 'byte[]':
            source += f'    @Override\n    public byte[] {field}() {{ return {field}.clone(); }}\n\n'
    if any(t == 'byte[]' for t, n, f in fields):
        source += f'    @Override\n    public boolean equals(Object other) {{\n        return other instanceof {name} that\n'
        source += ''.join(f'                && {"Arrays" if t == "byte[]" else "Objects"}.equals({n}, that.{n})\n' for t, n, f in fields).rstrip() + ';\n    }\n\n'
        source += '    @Override\n    public int hashCode() {\n        return Objects.hash(' + ', '.join(f'Arrays.hashCode({n})' if t == 'byte[]' else n for t, n, f in fields) + ');\n    }\n\n'
    source += '    @Override\n    public String toString() { return "' + name + '[redacted]"; }\n\n'
    source += '    public static Builder builder() { return new Builder(); }\n\n'
    source += '    public Builder toBuilder() {\n        return new Builder()' + ''.join(f'.{n}({n})' for t, n, f in fields) + ';\n    }\n\n'
    source += '    public static final class Builder {\n'
    for typ, field, meta in fields:
        source += f'        private {typ} {field};\n'
    source += '\n        private Builder() {}\n\n'
    for typ, field, meta in fields:
        source += f'        public Builder {field}({typ} value) {{\n            this.{field} = value;\n            return this;\n        }}\n\n'
    source += f'        public {name} build() {{\n            return new {name}(' + ', '.join(n for t, n, f in fields) + ');\n        }\n    }\n}\n'
    write(name, source)

# Adjacent-tagged Rust enums retain a strongly typed Java representation.
for name, spec in SCHEMA['unions'].items():
    variants = spec['variants']
    source = ('import com.fasterxml.jackson.annotation.JsonProperty;\n'
              'import com.fasterxml.jackson.annotation.JsonSubTypes;\n'
              'import com.fasterxml.jackson.annotation.JsonTypeInfo;\n'
              'import java.util.Objects;\n\n')
    source += f'/** Tagged {name} variants. */\n'
    source += '@JsonTypeInfo(use = JsonTypeInfo.Id.NAME, include = JsonTypeInfo.As.EXISTING_PROPERTY, property = "type")\n@JsonSubTypes({\n'
    source += ',\n'.join(f'    @JsonSubTypes.Type(value = {name}.{v[0]}.class, name = "{v[1]}")' for v in variants)
    source += f'\n}})\npublic sealed interface {name} {{\n'
    source += '    @JsonProperty("type")\n    String type();\n\n'
    if name == 'PasswordRecipe':
        source += '''    static PasswordRecipe random(long length, boolean includeDigits, boolean includeSymbols) {
        return new Random(new RandomPasswordOptions(includeDigits, includeSymbols, length));
    }

    static PasswordRecipe pin(long length) {
        return new Pin(new PinPasswordOptions(length));
    }

    static PasswordRecipe memorable(long wordCount, SeparatorType separator, boolean capitalize, WordListType wordList) {
        return new Memorable(new MemorablePasswordOptions(separator, capitalize, wordList, wordCount));
    }

'''
    elif name == 'ValidRecipient':
        source += '''    static ValidRecipient email(String email) { return new Email(new EmailRecipient(email)); }

    static ValidRecipient domain(String domain) { return new Domain(new DomainRecipient(domain)); }

'''
    elif name == 'ItemListFilter':
        source += '''    static ItemListFilter byState(boolean active, boolean archived) {
        return new ByState(new ItemStateFilter(active, archived));
    }

'''
    for variant, wire, payload in variants:
        prop = spec['property']
        field = '' if payload is None else f'{payload} {prop}'
        source += f'    record {variant}({field}) implements {name} {{\n'
        if payload:
            source += f'        public {variant} {{ Objects.requireNonNull({prop}, "{prop}"); }}\n'
        source += f'        @Override\n        public String type() {{ return "{wire}"; }}\n'
        source += f'        @Override\n        public String toString() {{ return "{name}.{variant}[redacted]"; }}\n    }}\n\n'
    source += '}\n'
    write(name, source)

permissions = SCHEMA['permissions']
write('VaultPermissions', '/** Bit flags to combine with the bitwise OR operator. */\n'
      'public final class VaultPermissions {\n    private VaultPermissions() {}\n\n'
      + ''.join(f'    public static final long {constant(n)} = {v}L;\n' for n, v in permissions.items()) + '}\n')
